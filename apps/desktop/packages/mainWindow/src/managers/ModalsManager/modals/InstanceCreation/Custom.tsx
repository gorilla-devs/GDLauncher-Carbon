import {
  Button,
  toast,
  Input,
  Select,
  SelectTrigger,
  SelectContent,
  SelectItem,
  SelectValue,
  Badge,
  PRESS_CLASSES
} from "@gd/ui"
import { ModalProps, useModal, useModalStackEntry } from "../.."
import { Trans, useTransContext } from "@gd/i18n"
import {
  createEffect,
  createMemo,
  createSignal,
  For,
  Match,
  on,
  onCleanup,
  untrack,
  Show,
  Switch
} from "solid-js"
import { apiFetch, extractErrorDisplay, rspc } from "@/utils/rspcClient"
import {
  CFFEModLoaderType,
  FEModdedManifestLoaderVersion,
  ManifestVersion,
  McType,
  ModLoader
} from "@gd/core_module/bindings"
import { blobToBase64, getModloaderDisplayName } from "@/utils/helpers"
import { useGDNavigate } from "@/managers/NavigationManager"
import ImagePicker from "@/components/ImagePicker"
import { editInstanceId, hasEditContext } from "./editInstanceId"
import { useGlobalStore } from "@/components/GlobalStoreContext"
import { getModloaderIcon } from "@/utils/sidebar"

type MappedMcVersions = ManifestVersion & { hasModloader?: boolean }

interface Instancetype {
  id?: string | number
  modloader: CFFEModLoaderType | undefined
  title: string | undefined
  mcVersion: string | undefined
  modloaderVersion: string | undefined
  img: string | undefined
}

const Custom = (
  props: Pick<ModalProps, "data"> & {
    onPendingChange?: (pending: boolean) => void
  }
) => {
  const [t] = useTransContext()
  const [mappedMcVersions, setMappedMcVersions] = createSignal<
    MappedMcVersions[]
  >([])

  const instanceData = () => props.data as Instancetype | undefined
  const editId = () => editInstanceId(instanceData())
  const invalidEdit = () =>
    hasEditContext(instanceData()) && editId() === undefined

  const [error, setError] = createSignal("")
  const [submitting, setSubmitting] = createSignal(false)
  const [createdId, setCreatedId] = createSignal<number | null>(null)
  const [preparationRecovery, setPreparationRecovery] = createSignal(false)
  const [createUncertain, setCreateUncertain] = createSignal(false)
  const editsLocked = () =>
    submitting() || createdId() !== null || createUncertain()
  const stackEntry = useModalStackEntry()
  let alive = true
  onCleanup(() => {
    alive = false
  })
  const setPending = (pending: boolean) => {
    setSubmitting(pending)
    props.onPendingChange?.(pending)
  }
  const openLibrary = () => {
    if (!alive || submitting()) return
    if (stackEntry && !stackEntry.closeOwn()) return
    navigator.navigate("/library")
  }
  const [bgPreview, setBgPreview] = createSignal<string | null>(
    instanceData()?.img || null
  )
  const [loader, setLoader] = createSignal<CFFEModLoaderType | undefined>(
    instanceData()?.modloader || undefined
  )
  const [chosenLoaderVersion, setChosenLoaderVersion] = createSignal(
    instanceData()?.modloaderVersion || undefined
  )
  const [mcVersion, setMcVersion] = createSignal(
    instanceData()?.mcVersion || ""
  )
  const [customTitle, setCustomTitle] = createSignal<string | null>(null)
  const [snapshotVersionFilter, setSnapshotVersionFilter] = createSignal(false)
  const [oldBetaVersionFilter, setOldBetaVersionFilter] = createSignal(false)
  const [oldAlphaVersionFilter, setOldAlphaVersionFilter] = createSignal(false)

  const autoGeneratedName = () =>
    `${getModloaderDisplayName(loader()) || "Vanilla"} ${mcVersion() || mappedMcVersions()?.[0]?.id}`

  const title = createMemo(() => {
    if (customTitle() !== null) return customTitle()
    if (instanceData()?.title) return instanceData()?.title

    return autoGeneratedName()
  })

  const modalsContext = useModal()
  const globalStore = useGlobalStore()
  const navigator = useGDNavigate()
  const forgeVersionsQuery = rspc.createQuery(() => ({
    queryKey: ["mc.getForgeVersions"],
    enabled: false
  }))
  const neoForgeVersionsQuery = rspc.createQuery(() => ({
    queryKey: ["mc.getNeoforgeVersions"],
    enabled: false
  }))
  const fabricVersionsQuery = rspc.createQuery(() => ({
    queryKey: ["mc.getFabricVersions"],
    enabled: false
  }))
  const quiltVersionsQuery = rspc.createQuery(() => ({
    queryKey: ["mc.getQuiltVersions"],
    enabled: false
  }))
  const DUMMY_META_VERSION = "${gdlauncher.gameVersion}"
  const loaderQuery = (kind = loader()) =>
    kind === "forge"
      ? forgeVersionsQuery
      : kind === "neoforge"
        ? neoForgeVersionsQuery
        : kind === "fabric"
          ? fabricVersionsQuery
          : kind === "quilt"
            ? quiltVersionsQuery
            : undefined
  const versionsFor = (
    release: string,
    kind = loader()
  ): FEModdedManifestLoaderVersion[] => {
    const query = loaderQuery(kind)
    if (!query || query.isError || query.isFetching || !query.data) return []
    const game = query.data.gameVersions.find((v) => v.id === release)
    if (!game) return []
    return kind === "fabric" || kind === "quilt"
      ? query.data.gameVersions.find((v) => v.id === DUMMY_META_VERSION)
          ?.loaders || []
      : game.loaders
  }
  const loaderVersions = createMemo(() => versionsFor(mcVersion()))
  const originalGame = () =>
    editId() !== undefined && mcVersion() === instanceData()?.mcVersion
  const readPair = () => ({
    release: mcVersion(),
    kind: loader(),
    version: chosenLoaderVersion()
  })
  const originalPair = (pair = readPair()) =>
    editId() !== undefined &&
    pair.release === instanceData()?.mcVersion &&
    pair.kind === instanceData()?.modloader &&
    pair.version === instanceData()?.modloaderVersion

  // A game/loader/metadata change selects a compatible fallback; a deliberate
  // loader selection is checked again at the dispatch boundary.
  createEffect(
    on([mcVersion, loader, loaderVersions], () => {
      if (untrack(() => editsLocked() || originalPair())) return
      const query = loaderQuery()
      if (loader() && (!query?.data || query.isFetching || query.isError))
        return
      const chosen = untrack(chosenLoaderVersion)
      if (!loaderVersions().some((v) => v.id === chosen))
        setChosenLoaderVersion(loaderVersions()[0]?.id)
    })
  )
  createEffect(() => {
    const all = globalStore.minecraftVersions.data || []
    const filtered = all.filter(
      (item) =>
        item.type === "release" ||
        (item.type === "snapshot" && snapshotVersionFilter()) ||
        (item.type === "old_beta" && oldBetaVersionFilter()) ||
        (item.type === "old_alpha" && oldAlphaVersionFilter())
    )
    // Keep the installed original available when its class is hidden or its
    // manifest is temporarily absent. Never silently edit its game version.
    if (originalGame() && !filtered.some((v) => v.id === mcVersion())) {
      filtered.unshift(
        all.find((v) => v.id === mcVersion()) || {
          id: mcVersion(),
          type: "release",
          release_time: ""
        }
      )
    }
    const games = loaderQuery()?.data?.gameVersions || []
    setMappedMcVersions(
      filtered.map((item) => ({
        ...item,
        hasModloader: games.some((v) => v.id === item.id)
      }))
    )
    if (!mcVersion() && filtered[0]) setMcVersion(filtered[0].id)
  })
  const pairIsValid = (pair = readPair()) => {
    if (invalidEdit()) return false
    if (originalPair(pair)) return true // Unchanged offline edits need no loader metadata.
    if (!globalStore.minecraftVersions.data?.some((v) => v.id === pair.release))
      return false
    if (!pair.kind) return true
    return versionsFor(pair.release, pair.kind).some(
      (v) => v.id === pair.version
    )
  }

  const modloaders: {
    label: string
    key: CFFEModLoaderType | undefined
  }[] = [
    { label: t("instances:_trn_vanilla"), key: undefined },
    { label: t("instances:_trn_forge"), key: "forge" },
    { label: t("instances:_trn_neoforge"), key: "neoforge" },
    { label: t("instances:_trn_fabric"), key: "fabric" },
    { label: t("instances:_trn_quilt"), key: "quilt" }
  ]

  const defaultGroup = rspc.createQuery(() => ({
    queryKey: ["instance.getDefaultGroup"]
  }))

  const prepareInstanceMutation = rspc.createMutation(() => ({
    mutationKey: ["instance.prepareInstance"]
  }))

  const createInstanceMutation = rspc.createMutation(() => ({
    mutationKey: ["instance.createInstance"]
  }))

  const updateInstanceMutation = rspc.createMutation(() => ({
    mutationKey: ["instance.updateInstance"]
  }))

  const mapTypeToColor = (
    type: McType,
    hasNoModloader: boolean | undefined
  ) => {
    return (
      <Switch>
        <Match when={type === "release"}>
          <span
            class="text-green-400"
            classList={{ "opacity-50": hasNoModloader }}
          >{`[${type}]`}</span>
        </Match>
        <Match when={type === "snapshot"}>
          <span
            class="text-yellow-400"
            classList={{ "opacity-50": hasNoModloader }}
          >{`[${type}]`}</span>
        </Match>
        <Match when={type === "old_alpha"}>
          <span
            class="text-purple-400"
            classList={{ "opacity-50": hasNoModloader }}
          >{`[${type}]`}</span>
        </Match>
        <Match when={type === "old_beta"}>
          <span
            class="text-red-400"
            classList={{ "opacity-50": hasNoModloader }}
          >{`[${type}]`}</span>
        </Match>
      </Switch>
    )
  }

  const [iconPath, setIconPath] = createSignal<string | null>(null)

  // Load preview without side effects - just for display
  const loadPreview = async (filePath: string) => {
    if (!alive || editsLocked()) return
    const response = await apiFetch(
      `/loadImage?path=${encodeURIComponent(filePath)}`
    )
    const blob = await response.blob()
    const b64 = (await blobToBase64(blob)) as string
    if (!alive || editsLocked()) return
    setBgPreview(`data:image/png;base64,${b64.substring(b64.indexOf(",") + 1)}`)
    setIconPath(filePath)
  }

  // Store icon in backend before create/update
  const storeIconForBackend = async (path = iconPath()) => {
    if (path) {
      const response = await apiFetch(
        `/instance/loadIcon?path=${encodeURIComponent(path)}`
      )
      if (!response.ok) {
        throw new Error("Failed to upload icon")
      }
    }
  }

  const isNameDiff = () => title() && title() !== instanceData()?.title
  const isMcVersionDiff = () =>
    mcVersion() && mcVersion() !== instanceData()?.mcVersion
  const isModloaderDiff = () => loader() !== instanceData()?.modloader
  const isModloaderVersionDiff = () =>
    chosenLoaderVersion() !== instanceData()?.modloaderVersion
  const isIconDiff = () => bgPreview() !== instanceData()?.img // not checking for null as it can be unset

  const isUpdatingWithDiffs = () => {
    if (editId() === undefined) return !invalidEdit()

    return (
      isNameDiff() ||
      isMcVersionDiff() ||
      isModloaderDiff() ||
      isModloaderVersionDiff() ||
      isIconDiff()
    )
  }

  const prepareCreated = async (instanceId: number) => {
    await prepareInstanceMutation.mutateAsync(instanceId)
    if (!alive) return
    // This RPC acknowledges preparation admission; installation continues in Library.
    if (stackEntry && !stackEntry.closeOwn()) return
    navigator.navigate("/library")
    toast.success(t("instances:_trn_custom_create_admitted"))
  }

  const retryPreparation = async () => {
    const instanceId = createdId()
    if (!alive || submitting() || instanceId === null) return
    setPending(true)
    setError("")
    try {
      await prepareCreated(instanceId)
    } catch {
      if (alive) {
        setPreparationRecovery(true)
        setError(t("instances:_trn_custom_prepare_failed"))
      }
    } finally {
      if (alive) setPending(false)
    }
  }

  const handleCreate = async () => {
    if (!alive || editsLocked()) return
    const pair = readPair()
    if (hasEditContext(instanceData()) || !pairIsValid(pair)) return
    const name = title()
    if (!name) {
      setError(t("errors:_trn_error.missing_field_title"))
      return
    }
    // Own the complete validated intent synchronously, before icon IO.
    const draft = {
      name,
      group:
        (props.data as { groupId?: number } | undefined)?.groupId ??
        defaultGroup.data ??
        1,
      icon: iconPath(),
      pair
    }
    setPending(true)
    setError("")
    let createSent = false
    try {
      await storeIconForBackend(draft.icon)
      if (!alive) return
      if (!pairIsValid(draft.pair)) {
        setError(t("instances:_trn_custom_create_failed"))
        return
      }
      createSent = true
      const instanceId = await createInstanceMutation.mutateAsync({
        group: draft.group,
        use_loaded_icon: true,
        notes: "",
        name: draft.name,
        version: {
          Version: {
            Standard: {
              release: draft.pair.release,
              modloaders: draft.pair.kind
                ? [
                    {
                      type_: draft.pair.kind,
                      version: draft.pair.version!
                    } as ModLoader
                  ]
                : []
            }
          }
        }
      })
      // Publication can precede either a lost acknowledgement or a later manager error.
      // Only the returned identity authorizes a same-instance preparation retry.
      if (!alive) return
      setCreatedId(instanceId)
      await prepareCreated(instanceId)
    } catch {
      if (!alive) return
      if (createdId() !== null) {
        setPreparationRecovery(true)
        setError(t("instances:_trn_custom_prepare_failed"))
      } else if (createSent) {
        setCreateUncertain(true)
        setError(t("instances:_trn_custom_create_uncertain"))
      } else {
        setError(t("instances:_trn_custom_create_failed"))
      }
    } finally {
      if (alive) setPending(false)
    }
  }

  const handleUpdate = async () => {
    const instance = editId()
    const pair = readPair()
    if (instance === undefined || !pairIsValid(pair)) return
    if (!title()) {
      setError("Fields must be filled in!")
      return
    }

    if (instance !== undefined) {
      setError("")

      try {
        // Store icon in backend before updating instance
        if (isIconDiff() && iconPath()) {
          await storeIconForBackend()
        }

        if (!pairIsValid(pair)) return
        await updateInstanceMutation.mutateAsync({
          instance,
          useLoadedIcon: isIconDiff() ? { Set: Boolean(bgPreview()) } : null,
          name: isNameDiff() ? { Set: title()! } : null,
          version:
            pair.release !== instanceData()?.mcVersion
              ? {
                  Set: pair.release
                }
              : null,
          modloader:
            pair.kind !== instanceData()?.modloader ||
            pair.version !== instanceData()?.modloaderVersion ||
            (pair.release !== instanceData()?.mcVersion && !!pair.kind)
              ? {
                  Set: pair.kind
                    ? ({
                        type_: pair.kind,
                        version: pair.version!
                      } as ModLoader)
                    : null
                }
              : null
        })
      } catch (err) {
        console.error(err)
        if (!alive) return
        // Keep the dialog and the user's choices, and say why the core
        // refused (for example an unfinished modpack update and its way out).
        setError(
          extractErrorDisplay(err).trim() ||
            t("instances:_trn_custom_update_failed")
        )
        return
      }
      modalsContext?.closeModal()
      toast.success("Instance successfully updated.")
      setError("")
      setCustomTitle("")
      setBgPreview(null)
      setMcVersion("")
      setChosenLoaderVersion("")
    }
  }

  createEffect(() => {
    if (instanceData()?.modloader === "forge") {
      forgeVersionsQuery.refetch()
    } else if (instanceData()?.modloader === "neoforge") {
      neoForgeVersionsQuery.refetch()
    } else if (instanceData()?.modloader === "fabric") {
      fabricVersionsQuery.refetch()
    } else if (instanceData()?.modloader === "quilt") {
      quiltVersionsQuery.refetch()
    }
  })

  return (
    <div class="flex h-[600px] w-full flex-col">
      <fieldset
        disabled={editsLocked()}
        class="m-0 min-h-0 min-w-0 border-0 flex flex-1 flex-col gap-3 overflow-y-auto p-4"
        style={{ "scrollbar-gutter": "stable" }}
      >
        {/* Instance Details Section */}
        <div class="flex flex-col gap-3">
          <div class="flex w-full items-center">
            <div class="border-t-1 border-lightSlate-400 flex-1 border-solid" />
            <span class="text-lightSlate-400 flex items-center gap-2 px-3 text-base">
              <div class="i-hugeicons:file-02 text-primary-500 text-sm" />
              <Trans key="general:_trn_about" />
            </span>
            <div class="border-t-1 border-lightSlate-400 flex-1 border-solid" />
          </div>
          <div class="flex w-full items-start gap-4">
            <ImagePicker
              imageUrl={bgPreview}
              onSelect={loadPreview}
              isLoading={editsLocked}
              onDelete={() => {
                if (editsLocked()) return
                setBgPreview(null)
                setIconPath(null)
              }}
              deletable={!editsLocked()}
              confirmDelete={false}
              sizeClass="h-20 w-20"
              dialogTitle={t("instances:_trn_select_icon")}
              placeholderIcon="i-hugeicons:image-01"
            />
            <div class="flex flex-1 flex-col gap-2">
              <label class="text-lightSlate-400 text-xs font-medium">
                <Trans key="instances:_trn_instance_name" />
              </label>
              <Input
                class="w-full"
                required
                data-testid="instance-creation-name"
                placeholder={t("instances:_trn_new_instance")}
                inputColor="bg-darkSlate-800"
                onInput={(e) => {
                  if (!editsLocked()) setCustomTitle(e.currentTarget.value)
                }}
                value={title()!}
                errorMessage={
                  error() && !title()
                    ? t("errors:_trn_error.missing_field_title")
                    : undefined
                }
              />
            </div>
          </div>
        </div>

        {/* Minecraft Version Section */}
        <div class="flex flex-col gap-3">
          <div class="flex w-full items-center">
            <div class="border-t-1 border-lightSlate-400 flex-1 border-solid" />
            <span class="text-lightSlate-400 flex items-center gap-2 px-3 text-base">
              <div class="i-hugeicons:minecraft text-primary-500 text-sm" />
              <Trans key="instances:_trn_instance_mc_version" />
            </span>
            <div class="border-t-1 border-lightSlate-400 flex-1 border-solid" />
          </div>
          <div class="flex w-full flex-col gap-2">
            <Select
              value={mcVersion()}
              onChange={(value) => {
                if (!value || editsLocked()) return
                if (mappedMcVersions().some((v) => v.id === value))
                  setMcVersion(value)
              }}
              options={mappedMcVersions().map((v) => v.id)}
              placeholder={t("errors:_trn_error.no_mc_versions")}
              disabled={Boolean(
                ((forgeVersionsQuery.isFetching ||
                  fabricVersionsQuery.isFetching ||
                  quiltVersionsQuery.isFetching ||
                  neoForgeVersionsQuery.isFetching) &&
                  loader()) ||
                mappedMcVersions().length === 0
              )}
              disallowEmptySelection={true}
              itemComponent={(itemProps) => {
                const version = mappedMcVersions().find(
                  (v) => v.id === itemProps.item.rawValue
                )
                return (
                  <SelectItem
                    item={itemProps.item}
                    data-testid={`instance-creation-version-option-${itemProps.item.rawValue}`}
                  >
                    <div class="flex w-full items-center justify-between gap-2">
                      <span
                        classList={{
                          "text-lightSlate-700": Boolean(
                            version && !version.hasModloader && loader()
                          )
                        }}
                      >
                        {itemProps.item.rawValue}
                      </span>
                      <span class="shrink-0">
                        {version &&
                          mapTypeToColor(
                            version.type,
                            Boolean(!version.hasModloader && loader())
                          )}
                      </span>
                    </div>
                  </SelectItem>
                )
              }}
            >
              <SelectTrigger data-testid="instance-creation-version-trigger">
                <SelectValue<string>>
                  {(state) => state.selectedOption()}
                </SelectValue>
              </SelectTrigger>
              <SelectContent />
            </Select>
            <div class="flex flex-wrap items-center gap-2">
              <Badge
                variant={snapshotVersionFilter() ? "default" : "secondary"}
                class="cursor-pointer px-2.5 py-1 text-xs"
                onClick={() =>
                  !editsLocked() &&
                  setSnapshotVersionFilter(!snapshotVersionFilter())
                }
                title="Snapshot versions"
              >
                <div class="flex items-center gap-1">
                  <div class="i-hugeicons:test-tube text-xs" />
                  <span>
                    <Trans key="instances:_trn_version_type_snapshot" />
                  </span>
                </div>
              </Badge>
              <Badge
                variant={oldAlphaVersionFilter() ? "default" : "secondary"}
                class="cursor-pointer px-2.5 py-1 text-xs"
                onClick={() =>
                  !editsLocked() &&
                  setOldAlphaVersionFilter(!oldAlphaVersionFilter())
                }
                title="Old alpha versions"
              >
                <div class="flex items-center gap-1">
                  <div class="i-hugeicons:alpha text-xs" />
                  <span>
                    <Trans key="instances:_trn_version_type_alpha" />
                  </span>
                </div>
              </Badge>
              <Badge
                variant={oldBetaVersionFilter() ? "default" : "secondary"}
                class="cursor-pointer px-2.5 py-1 text-xs"
                onClick={() =>
                  !editsLocked() &&
                  setOldBetaVersionFilter(!oldBetaVersionFilter())
                }
                title="Old beta versions"
              >
                <div class="flex items-center gap-1">
                  <div class="i-hugeicons:beta text-xs" />
                  <span>
                    <Trans key="instances:_trn_version_type_beta" />
                  </span>
                </div>
              </Badge>
            </div>
          </div>
        </div>

        {/* Modloader Section */}
        <div class="flex flex-col gap-3">
          <div class="flex w-full items-center">
            <div class="border-t-1 border-lightSlate-400 flex-1 border-solid" />
            <span class="text-lightSlate-400 flex items-center gap-2 px-3 text-base">
              <div class="i-hugeicons:package text-primary-500 text-sm" />
              <Trans key="content:_trn_modloader" />
            </span>
            <div class="border-t-1 border-lightSlate-400 flex-1 border-solid" />
          </div>
          <div class="grid grid-cols-5 gap-3">
            <For each={modloaders}>
              {(modloader) => (
                <button
                  class={`bg-darkSlate-800 hover:outline-darkSlate-600 hover:bg-darkSlate-700 group flex flex-col items-center gap-2 rounded-lg border-0 border-transparent p-3 outline-none ${PRESS_CLASSES}`}
                  classList={{
                    "!outline-primary-500": loader() === modloader.key
                  }}
                  data-testid={`instance-creation-loader-${modloader.key ?? "vanilla"}`}
                  onClick={() => {
                    if (editsLocked()) return
                    if (modloader.key === "forge") {
                      forgeVersionsQuery.refetch()
                    } else if (modloader.key === "neoforge") {
                      neoForgeVersionsQuery.refetch()
                    } else if (modloader.key === "fabric") {
                      fabricVersionsQuery.refetch()
                    } else if (modloader.key === "quilt") {
                      quiltVersionsQuery.refetch()
                    }
                    setLoader(!modloader.key ? undefined : modloader.key)
                  }}
                >
                  <img
                    class="h-8 w-8 transition-transform group-hover:scale-110"
                    src={getModloaderIcon(modloader.key || "vanilla")}
                    alt={modloader.label}
                  />
                  <span class="text-lightSlate-300 group-hover:text-lightSlate-50 text-xs font-medium transition-colors">
                    {modloader.label}
                  </span>
                </button>
              )}
            </For>
          </div>

          {/* Modloader Version - Appears inline when modloader selected */}
          <Show when={loader()}>
            <div class="border-primary-500/30 flex flex-col gap-2 border-l-2 pl-4">
              <label class="text-lightSlate-400 text-xs font-medium">
                <Trans key="instances:_trn_instance_loader_version" />
              </label>
              <Switch>
                <Match
                  when={
                    (forgeVersionsQuery.isFetching ||
                      fabricVersionsQuery.isFetching ||
                      quiltVersionsQuery.isFetching ||
                      neoForgeVersionsQuery.isFetching) &&
                    loaderVersions().length === 0
                  }
                >
                  <div class="bg-darkSlate-800 h-10 animate-pulse rounded-md" />
                </Match>
                <Match when={loaderVersions().length > 0}>
                  <Select
                    value={chosenLoaderVersion()}
                    onChange={(value) =>
                      !editsLocked() && value && setChosenLoaderVersion(value)
                    }
                    options={loaderVersions()?.map((v) => v.id) || []}
                    disabled={
                      forgeVersionsQuery.isFetching ||
                      fabricVersionsQuery.isFetching ||
                      quiltVersionsQuery.isFetching ||
                      neoForgeVersionsQuery.isFetching ||
                      !loaderVersions()
                    }
                    disallowEmptySelection={true}
                    itemComponent={(itemProps) => (
                      <SelectItem
                        item={itemProps.item}
                        data-testid={`instance-creation-loader-version-option-${itemProps.item.rawValue}`}
                      >
                        {itemProps.item.rawValue}
                      </SelectItem>
                    )}
                  >
                    <SelectTrigger data-testid="instance-creation-loader-version-trigger">
                      <SelectValue<string>>
                        {(state) => state.selectedOption()}
                      </SelectValue>
                    </SelectTrigger>
                    <SelectContent />
                  </Select>
                </Match>
                <Match
                  when={
                    loaderVersions().length === 0 &&
                    !forgeVersionsQuery.isFetching &&
                    !fabricVersionsQuery.isFetching &&
                    !quiltVersionsQuery.isFetching &&
                    !neoForgeVersionsQuery.isFetching
                  }
                >
                  <div class="text-lightSlate-500 bg-darkSlate-800 flex items-center gap-2 rounded-md px-3 py-2 text-sm">
                    <div class="i-hugeicons:alert-circle text-yellow-500" />
                    <span>
                      <Trans
                        key="instances:_trn_no_versions_for_mc"
                        options={{ version: mcVersion() }}
                      />
                    </span>
                  </div>
                </Match>
              </Switch>
            </div>
          </Show>
        </div>
      </fieldset>

      <Show when={error() && title()}>
        <p role="alert" class="m-0 px-4 pb-3 text-sm text-red-400">
          {error()}
        </p>
      </Show>
      <Show when={createdId() !== null}>
        <p class="m-0 px-4 pb-3 text-sm">
          <Trans
            key="instances:_trn_custom_existing_snapshot"
            options={{
              name: title(),
              interpolation: { escapeValue: false }
            }}
          />
        </p>
      </Show>

      {/* Buttons - outside scrollable area */}
      <div class="flex w-full flex-wrap justify-end gap-2 px-4 pb-4 pt-0">
        <Show when={preparationRecovery()}>
          <Button
            data-testid="instance-creation-retry"
            loading={submitting()}
            onClick={retryPreparation}
          >
            <Trans key="instances:_trn_custom_retry_preparation" />
          </Button>
        </Show>
        <Show when={createdId() !== null || createUncertain()}>
          <Button
            data-testid="instance-creation-library"
            disabled={submitting()}
            onClick={openLibrary}
          >
            <Trans key="instances:_trn_custom_view_library" />
          </Button>
        </Show>
        <Show when={createUncertain()}>
          <Button
            data-testid="instance-creation-fresh-copy"
            disabled={submitting()}
            onClick={() => {
              if (!alive || submitting()) return
              setCreateUncertain(false)
              setError("")
            }}
          >
            <Trans key="instances:_trn_custom_fresh_copy" />
          </Button>
        </Show>
        <Button
          disabled={editsLocked() || !pairIsValid() || !isUpdatingWithDiffs()}
          loading={submitting() && !preparationRecovery()}
          type="primary"
          data-testid="instance-creation-submit"
          style={{ width: "100%", "max-width": "200px" }}
          onClick={() => {
            if (editId() !== undefined) handleUpdate()
            else handleCreate()
          }}
        >
          <Switch>
            <Match when={editId() === undefined}>
              <div class="flex items-center gap-1.5">
                <div class="i-hugeicons:add-01" />
                <Trans key="instances:_trn_instance_modal_instance_creation_create" />
              </div>
            </Match>
            <Match when={editId() !== undefined}>
              <div class="flex items-center gap-1.5">
                <div class="i-hugeicons:pencil-edit-01" />
                <Trans key="instances:_trn_instance_modal_instance_update" />
              </div>
            </Match>
          </Switch>
        </Button>
      </div>
    </div>
  )
}

export default Custom
