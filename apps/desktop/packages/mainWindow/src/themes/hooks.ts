// Identity tokens say which one an element is, so a theme doesn't have to
// count siblings: `<base>.<id>`, next to the base hook, with the id in
// kebab-case. They never come and go while the element is on the page.

/** A name in kebab-case: `instanceCreation` and `modpack_version_update`
 *  become `instance-creation` and `modpack-version-update`. */
export function kebabId(name: string): string {
  return name
    .replace(/_/g, "-")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1-$2")
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .toLowerCase()
    .replace(/^-+/, "")
}

/** The identity token of an element: `identityHook("modal", "instanceCreation")`
 *  is `"modal.instance-creation"`. */
export function identityHook(base: string, id: string): string {
  return `${base}.${kebabId(id)}`
}

