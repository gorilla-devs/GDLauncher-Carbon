/** The hook tokens of a tile's play button, by the state it shows. */
export function tilePlayHooks(running: boolean, busy: boolean): string {
  return (
    "library.tile.play" +
    (running
      ? " library.tile.play.running"
      : busy
        ? " library.tile.play.busy"
        : "")
  )
}

